# ── Name → color lookup ─────────────────────────────────────────────────────

COLOR_NAMES: Dict[str, RGBColor] = {
    name: value
    for name, value in globals().items()
    if isinstance(value, tuple)
    and len(value) == 3
    and not name.startswith("_")
    and name not in ("RGBColor", "ALL_COLORS", "COLOR_NAMES")
}
